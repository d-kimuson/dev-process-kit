/** When a story comment was written, to the minute. */
const commentDate = (locale: string, at: string): string =>
  new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(at));

/**
 * A date on a chart's time axis, as precise as its ticks: the day for day and
 * week ticks, the month (with the year in January) for month and quarter
 * ticks, the year for year ticks.
 */
const axisDate = (locale: string, at: number, unit: AxisUnit): string => {
  const date = new Date(at);
  switch (unit) {
    case 'day':
    case 'week':
    case 'biweek':
      return `${date.getMonth() + 1}/${date.getDate()}`;
    case 'month':
    case 'quarter':
      return new Intl.DateTimeFormat(locale, {
        month: 'short',
        ...(date.getMonth() === 0 ? { year: 'numeric' } : {}),
      }).format(date);
    case 'year':
      return new Intl.DateTimeFormat(locale, { year: 'numeric' }).format(date);
  }
};

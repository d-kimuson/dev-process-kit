import { describe, expect, it } from 'vitest';

import { documentTokens, themeScope, tokens } from './theme';

/**
 * `themeScope` is the third place (besides `:host` in `tokens` and `:root` in
 * `documentTokens`) that re-derives `--dpk-accent*` / `--dpk-blue*` from the
 * two brand inputs — for content with neither boundary (slotted light DOM,
 * an app screen a template renders with its own brand). The one thing worth
 * guarding here is that it never drifts from the other two: all three must
 * emit the exact same derived-token declarations, because a scoped brand
 * should look identical whether it is set on a component, the document, or a
 * `data-dpk-theme` subtree.
 */
describe('themeScope', () => {
  const css = themeScope.cssText;

  it('scopes to the data-dpk-theme attribute hook', () => {
    expect(css).toContain('[data-dpk-theme]');
  });

  it('declares the same derived accent/blue tokens as tokens and documentTokens', () => {
    const derivedTokens = [
      '--dpk-accent:',
      '--dpk-accent-strong:',
      '--dpk-accent-bright:',
      '--dpk-accent-soft:',
      '--dpk-accent-ink:',
      '--dpk-blue:',
      '--dpk-blue-strong:',
      '--dpk-blue-soft:',
    ];

    for (const declaration of derivedTokens) {
      expect(css).toContain(declaration);
    }

    // The brand-derivation block is generated by the same `brandTokens()` call in all
    // three exports, so it must appear byte-for-byte identically in each — this is
    // the guard against the three ever drifting apart.
    const brandBlock = (source: string) => {
      const start = source.indexOf('--dpk-accent:');
      const end = source.indexOf('--dpk-blue-soft:');
      return source.slice(start, end);
    };

    expect(brandBlock(css)).toBe(brandBlock(tokens.cssText));
    expect(brandBlock(css)).toBe(brandBlock(documentTokens.cssText));
  });

  it('redeclares the brand derivation again under the light-dark() @supports block', () => {
    const occurrences = css.split('--dpk-accent:').length - 1;
    expect(occurrences).toBe(2);
    expect(css).toContain('@supports (color: light-dark(#000, #fff))');
  });
});
